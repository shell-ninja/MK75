def render_svg_pixmap(name: str, color: str = "#9CA3AF", size: int = 18) -> QPixmap:
    """Renders named SVG string onto transparent QPixmap with specified color & dimensions."""
    raw_svg = SVG_ICONS.get(name, SVG_ICONS["keyboard"])
    themed_svg = raw_svg.replace("currentColor", color)
    renderer = QSvgRenderer(QByteArray(themed_svg.encode("utf-8")))

    pix = QPixmap(size, size)
    pix.fill(QColor(0, 0, 0, 0))
    painter = QPainter(pix)
    painter.setRenderHint(QPainter.Antialiasing, True)
    renderer.render(painter)
    painter.end()
    return pix

def get_icon(name: str, normal_color: str = "#8A94A6", active_color: str = "#FFFFFF", size: int = 18) -> QIcon:
    """Creates a dual-state QIcon from an SVG definition (Normal & Selected)."""
    icon = QIcon()
    pix_normal = render_svg_pixmap(name, color=normal_color, size=size)
    pix_active = render_svg_pixmap(name, color=active_color, size=size)

    icon.addPixmap(pix_normal, QIcon.Normal, QIcon.Off)
    icon.addPixmap(pix_active, QIcon.Normal, QIcon.On)
    icon.addPixmap(pix_active, QIcon.Active, QIcon.On)
    icon.addPixmap(pix_active, QIcon.Selected, QIcon.On)
    return icon
